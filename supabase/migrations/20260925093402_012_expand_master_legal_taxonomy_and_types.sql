insert into public.legal_categories
  (taxonomy_id,code,name_fa,sort_order,is_active,metadata)
select
  t.id,
  src.code,
  src.name_fa,
  src.code::integer,
  true,
  jsonb_build_object(
    'catalog_total_count',src.total_count,
    'catalog_new_count',src.new_count,
    'legacy_app_mapping',src.legacy_mapping,
    'change_note',src.change_note,
    'taxonomy_version','1405-07-03-expanded-v1',
    'category_role',case when src.code='64' then 'curation' else 'subject' end
  )
from t cross join src
on conflict (taxonomy_id,code) where code is not null do update
set name_fa=excluded.name_fa,
    sort_order=excluded.sort_order,
    is_active=true,
    metadata=excluded.metadata,
    updated_at=now();

